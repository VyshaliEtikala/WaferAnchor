results = []

for i, record in enumerate(metadata):

    ref_path = image_base / record["ref"]
    search_path = image_base / record["search"]

    predicted, score = predict_location(
        ref_path,
        search_path
    )

    ground_truth = (
        record["center"]["x"],
        record["center"]["y"]
    )

    error = np.sqrt(
        (predicted[0] - ground_truth[0]) ** 2 +
        (predicted[1] - ground_truth[1]) ** 2
    )

    results.append({
        "Pair": i,
        "Predicted X": predicted[0],
        "Predicted Y": predicted[1],
        "Ground Truth X": ground_truth[0],
        "Ground Truth Y": ground_truth[1],
        "Error (pixels)": error,
        "Matching Score": score
    })


