def predict_location(ref_path, search_path):
    ref = cv2.imread(str(ref_path), cv2.IMREAD_GRAYSCALE)
    search = cv2.imread(str(search_path), cv2.IMREAD_GRAYSCALE)

    # Normalize both images
    ref = cv2.GaussianBlur(ref, (3, 3), 0)
    search = cv2.GaussianBlur(search, (3, 3), 0)

    ref = cv2.normalize(ref, None, 0, 255, cv2.NORM_MINMAX)
    search = cv2.normalize(search, None, 0, 255, cv2.NORM_MINMAX)

    best_score = -1
    best_xy = None

    # Multi-scale matching
    for scale in np.linspace(0.82, 1.18, 19):
        h, w = ref.shape
        nw = max(16, int(w * scale))
        nh = max(16, int(h * scale))

        if nw >= search.shape[1] or nh >= search.shape[0]:
            continue

        template = cv2.resize(ref, (nw, nh))

        result = cv2.matchTemplate(
            search,
            template,
            cv2.TM_CCOEFF_NORMED
        )

        _, score, _, location = cv2.minMaxLoc(result)

        if score > best_score:
            best_score = score
            x, y = location
            best_xy = (
                x + nw / 2,
                y + nh / 2
            )

    return best_xy, best_score


